def find_interpreter() -> str:
	"""Returns the path to a suitable Python interpreter, preferring a locally installed one."""
	localappdata = os.getenv('LOCALAPPDATA', '')
	if localappdata:
		base = os.path.join(localappdata, 'Programs', 'Python')
		for ver in ('Python314', 'Python313', 'Python312', 'Python311', 'Python310'):
			candidate = os.path.join(base, ver, 'python.exe')
			if os.path.exists(candidate):
				return candidate
	return sys.executable


def find_wheel(explicit: str | None) -> str:
	"""Returns the rsmxo wheel path (explicit or the newest one found in ./dist)."""
	if explicit:
		if not os.path.exists(explicit):
			raise FileNotFoundError(f'Wheel not found: {explicit}')
		return os.path.abspath(explicit)

	script_dir = os.path.dirname(os.path.abspath(__file__))
	dist_dir = os.path.join(script_dir, 'dist')
	if not os.path.isdir(dist_dir):
		dist_dir = os.path.abspath(os.path.join(script_dir, '..', 'dist'))
	wheels = [os.path.join(dist_dir, f) for f in os.listdir(dist_dir) if f.lower().endswith('.whl')]
	if not wheels:
		raise FileNotFoundError(f'No wheel found in {dist_dir}. Build the package first (BuildSetup.bat).')
	wheels.sort(key=os.path.getmtime, reverse=True)
	return wheels[0]


def _ensure_readable(wheel: str) -> str:
	"""Fails early when the wheel exists but cannot be opened (locked dist file)."""
	try:
		with open(wheel, 'rb') as fh:
			fh.read(16)
	except PermissionError as exc:
		raise PermissionError(
			f'Cannot read wheel: {wheel}. Rebuild it with BuildSetup.bat, '
			f'or pass --wheel pointing at a readable copy.'
		) from exc
	return wheel


def bootstrap(args: argparse.Namespace) -> None:
	"""Creates a venv, installs the product with all extras, then renders the PDF inside it."""
	wheel = _ensure_readable(find_wheel(args.wheel))
	version = extract_version(wheel)
	output = os.path.abspath(args.output)
	xml_output = os.path.abspath(args.xml_output)

	interpreter = find_interpreter()
	venv_dir = os.path.join(tempfile.gettempdir(), 'RsMxo_OSA_venv')

	print(f'Interpreter : {interpreter}')
	print(f'Wheel       : {wheel}  (version {version})')
	print(f'Output PDF  : {output}')
	print(f'Output XML  : {xml_output}')
	print(f'Venv        : {venv_dir}')

	if os.path.exists(venv_dir):
		shutil.rmtree(venv_dir)

	print('\n[1/4] Creating virtual environment...')
	subprocess.check_call([interpreter, '-m', 'venv', venv_dir])

	venv_py = os.path.join(venv_dir, 'Scripts', 'python.exe')
	if not os.path.exists(venv_py):
		venv_py = os.path.join(venv_dir, 'bin', 'python')

	print('\n[2/4] Upgrading pip...')
	subprocess.check_call([venv_py, '-m', 'pip', 'install', '--upgrade', 'pip', '--quiet'])

	print('\n[3/4] Installing rsmxo + reportlab (resolving full dependency tree)...')
	subprocess.check_call([venv_py, '-m', 'pip', 'install', wheel, 'reportlab'])

	print('\n[4/4] Collecting license data and rendering PDF + inventory XML...')
	subprocess.check_call([
		venv_py, os.path.abspath(__file__), '--internal',
		'--output', output,
		'--xml-output', xml_output,
		'--doc-version', version,
	])

	print(f'\nDone. PDF written to: {output}')
	print(f'Done. XML written to: {xml_output}')


def extract_version(wheel_path: str) -> str:
	"""Extracts the version from a wheel filename such as rsmxo-2.11.0-py3-none-any.whl."""
	name = os.path.basename(wheel_path)
	m = re.match(r'[^-]+-([^-]+)-', name)
	return m.group(1) if m else '0.0.0'


