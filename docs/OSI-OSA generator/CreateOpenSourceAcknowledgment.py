# SPDX identifier -> human readable license name used in the tables and section headings.
_SPDX_NAMES = {
	'MIT': 'MIT License',
	'BSD-2-Clause': 'BSD 2-Clause "Simplified" License',
	'BSD-3-Clause': 'BSD 3-Clause "New" or "Revised" License',
	'Apache-2.0': 'Apache License 2.0',
	'MPL-2.0': 'Mozilla Public License 2.0',
	'ISC': 'ISC License',
	'Python-2.0': 'Python Software Foundation License 2.0',
	'PSF-2.0': 'Python Software Foundation License 2.0',
	'LGPL-2.1-only': 'GNU Lesser General Public License v2.1',
	'LGPL-3.0-only': 'GNU Lesser General Public License v3.0',
	'0BSD': 'BSD Zero Clause License',
	'Unlicense': 'The Unlicense',
}

# Maps a couple of common Trove classifiers to SPDX identifiers.
_CLASSIFIER_TO_SPDX = {
	'License :: OSI Approved :: MIT License': 'MIT',
	'License :: OSI Approved :: BSD License': 'BSD-3-Clause',
	'License :: OSI Approved :: Apache Software License': 'Apache-2.0',
	'License :: OSI Approved :: Mozilla Public License 2.0 (MPL 2.0)': 'MPL-2.0',
	'License :: OSI Approved :: ISC License (ISCL)': 'ISC',
	'License :: OSI Approved :: Python Software Foundation License': 'Python-2.0',
	'License :: OSI Approved :: GNU Lesser General Public License v2 or later (LGPLv2+)': 'LGPL-2.1-only',
	'License :: OSI Approved :: GNU Lesser General Public License v3 (LGPLv3)': 'LGPL-3.0-only',
}


def normalize_spdx(raw: str) -> str:
	"""Best-effort normalization of a license string to an SPDX identifier."""
	if not raw:
		return ''
	text = raw.strip()
	# License-Expression fields are already (mostly) SPDX; take the first token of an OR/AND expr.
	token = re.split(r'\s+(?:OR|AND)\s+', text, flags=re.IGNORECASE)[0].strip().strip('()')
	known = {k.lower(): k for k in _SPDX_NAMES}
	if token.lower() in known:
		return known[token.lower()]
	low = text.lower()
	if 'apache' in low:
		return 'Apache-2.0'
	if 'unlicense' in low or 'public domain' in low:
		return 'Unlicense'
	if 'mozilla' in low or 'mpl' in low:
		return 'MPL-2.0'
	if 'permission is hereby granted, free of charge' in low or 'mit' in low:
		return 'MIT'
	if 'bsd' in low and '2' in low:
		return 'BSD-2-Clause'
	if 'bsd' in low:
		return 'BSD-3-Clause'
	if 'isc' in low or 'permission to use, copy, modify, and/or distribute' in low:
		return 'ISC'
	if 'python software foundation' in low or 'psf' in low:
		return 'Python-2.0'
	return token or text


def _requirement_name(requirement: str) -> str:
	"""Returns the distribution name of a Requires-Dist entry, or '' when it is an extra."""
	marker = requirement.split(';', 1)[1] if ';' in requirement else ''
	if re.search(r'(?i)\bextra\s*==', marker):
		return ''
	base = requirement.split(';', 1)[0].strip()
	name = re.split(r'[\s<>=!~\[]', base, maxsplit=1)[0].strip()
	return name


def _product_dependency_names() -> set[str] | None:
	"""Lower-case names of the installed product's transitive requirements.

	Returns None when the product distribution is not installed, so the caller can
	fall back to every installed distribution.
	"""
	from importlib import metadata as im

	try:
		root = im.distribution('rsmxo')
	except im.PackageNotFoundError:
		return None

	names: set[str] = set()
	pending = [root]
	seen: set[str] = set()
	while pending:
		dist = pending.pop()
		key = (dist.metadata.get('Name') or '').strip().lower()
		if not key or key in seen:
			continue
		seen.add(key)
		for requirement in (dist.requires or []):
			req_name = _requirement_name(requirement)
			if not req_name:
				continue
			try:
				child = im.distribution(req_name)
			except im.PackageNotFoundError:
				continue
			child_name = (child.metadata.get('Name') or req_name).strip()
			names.add(child_name.lower())
			pending.append(child)
	return names


def collect_packages() -> list[dict]:
	"""Enumerates installed distributions and gathers name/version/license/copyright/text."""
	from importlib import metadata as im

	allowed = _product_dependency_names()
	packages: dict[str, dict] = {}
	for dist in im.distributions():
		meta = dist.metadata
		name = (meta.get('Name') or '').strip()
		if not name or name.lower() in _EXCLUDED_DISTS:
			continue
		if allowed is not None and name.lower() not in allowed:
			continue
		if name.lower() in packages:
			continue

		license_text = _read_license_text(dist, meta)
		spdx = _resolve_spdx(meta)
		if not spdx and license_text:
			# Metadata carried no usable license id: infer it from the license text itself,
			# but only accept a recognized SPDX identifier.
			inferred = normalize_spdx(license_text)
			if inferred in _SPDX_NAMES:
				spdx = inferred
		if not license_text and spdx in _FALLBACK_LICENSE_TEXTS:
			license_text = _FALLBACK_LICENSE_TEXTS[spdx]
		copyright_line = _extract_copyright(license_text) or _extract_copyright(meta.get('Author') or '')

		packages[name.lower()] = {
			'name': name,
			'version': (dist.version or '').strip(),
			'spdx': spdx,
			'license_name': _SPDX_NAMES.get(spdx, spdx or 'See package'),
			'license_text': license_text or _FALLBACK_LICENSE_TEXTS.get(spdx, ''),
			'copyright': copyright_line or '',
			'origin': _extract_origin(meta),
		}

	return sorted(packages.values(), key=lambda p: p['name'].lower())


def _resolve_spdx(meta) -> str:
	expr = meta.get('License-Expression')
	if expr:
		return normalize_spdx(expr)
	classifiers = meta.get_all('Classifier') or []
	for c in classifiers:
		if c in _CLASSIFIER_TO_SPDX:
			return _CLASSIFIER_TO_SPDX[c]
	for c in classifiers:
		if c.startswith('License :: OSI Approved ::'):
			return normalize_spdx(c.split('::')[-1])
	lic = meta.get('License')
	if lic and len(lic) < 120:
		return normalize_spdx(lic)
	return ''


def _read_license_text(dist, meta) -> str:
	"""Reads the verbatim license file shipped inside the distribution's dist-info, if any."""
	candidates: list[str] = []
	for lf in (meta.get_all('License-File') or []):
		base = os.path.basename(lf)
		candidates += [lf, f'licenses/{lf}', base, f'licenses/{base}']

	# Also scan the recorded files for anything that looks like a license.
	try:
		for f in (dist.files or []):
			fname = os.path.basename(str(f))
			if re.match(r'(?i)(license|licence|copying|notice)', fname):
				candidates.append(str(f))
				candidates.append(fname)
				candidates.append(f'licenses/{fname}')
	except Exception:
		pass

	seen: set[str] = set()
	for cand in candidates:
		if cand in seen:
			continue
		seen.add(cand)
		text = _safe_read(dist, cand)
		if text and len(text.strip()) > 40:
			return text.strip()
	return ''


def _safe_read(dist, rel: str) -> str:
	try:
		text = dist.read_text(rel)
		if text:
			return text
	except Exception:
		pass
	try:
		path = dist.locate_file(rel)
		if path and os.path.exists(path):
			with open(path, 'r', encoding='utf-8', errors='replace') as fh:
				return fh.read()
	except Exception:
		pass
	return ''


def _extract_copyright(text: str) -> str:
	if not text:
		return ''
	for line in text.splitlines():
		stripped = line.strip()
		if not re.match(r'(?i)copyright\b', stripped) or len(stripped) <= len('copyright'):
			continue
		# Skip generic placeholders like "Copyright [yyyy] [name of copyright owner]".
		if '[' in stripped and ']' in stripped:
			continue
		# A real notice carries a holder: require a year or a (c)/copyright symbol,
		# which filters out license-body prose that merely mentions the word "copyright".
		if not (re.search(r'\b\d{4}\b', stripped) or re.search(r'(?i)\(c\)|\u00a9', stripped)):
			continue
		return re.sub(r'\s+', ' ', stripped)
	return ''


def _extract_origin(meta) -> str:
	"""Returns the project's origin URL (homepage / repository) from the package metadata."""
	home = (meta.get('Home-page') or '').strip()
	if home:
		return home

	# Newer metadata stores URLs as ``Project-URL`` entries of the form "Label, URL".
	labeled: dict[str, str] = {}
	order: list[str] = []
	for entry in (meta.get_all('Project-URL') or []):
		if ',' in entry:
			label, url = entry.split(',', 1)
			key = label.strip().lower()
			labeled[key] = url.strip()
			order.append(key)
	for key in ('homepage', 'home', 'source', 'source code', 'repository', 'documentation', 'download'):
		if key in labeled:
			return labeled[key]
	if order:
		return labeled[order[0]]
	return ''


