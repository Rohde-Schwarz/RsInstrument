"""Generates the Open Source Acknowledgment (OSA) PDF and the OSI inventory XML for RsMxo.

The documents list every third-party open source package that gets installed together with
the ``rsmxo`` wheel (the full transitive dependency tree of its declared requirements),
together with the verbatim license texts and copyright notices.

Two artifacts are produced:

* the human-readable Open Source Acknowledgment PDF, and
* an OSI inventory XML (``Inventory.xsd`` schema) listing every module with its version,
  license reference, origin URL and copyright.

How it works
------------
The script works in two phases:

1. Bootstrap (run with any interpreter): creates a fresh virtual environment, installs the
   locally built rsmxo wheel plus ``reportlab``, then re-invokes this same file with the
   venv interpreter and the ``--internal`` flag.
2. Internal (run with the venv interpreter): enumerates the installed distributions via
   ``importlib.metadata``, harvests license/copyright/origin information and renders the PDF
   and the inventory XML.

Usage
-----
    py CreateOpenSourceAcknowledgment.py

Optional arguments::

    --wheel <path>       Path to the rsmxo wheel (default: newest wheel in ./dist)
    --output <path>      Output PDF path (default: ./RsMxo_OpenSourceAcknowledgment.pdf)
    --xml-output <path>  Output inventory XML path
                         (default: ./RsMxo_OpenSourceInventory.xml)
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile

__version__ = '1.0.0'

# Distributions that belong to the build/tooling and are not part of the shipped product.
_EXCLUDED_DISTS = {'rsmxo', 'pip', 'setuptools', 'wheel', 'reportlab', 'pkg_resources'}

PRODUCT_NAME = 'Autogenerated Instrument Drivers Python'
PRODUCT_SUBTITLE = ''
DOC_TITLE = 'Open Source Acknowledgment'
MATERIAL_NUMBER = '1705.3717.00'

