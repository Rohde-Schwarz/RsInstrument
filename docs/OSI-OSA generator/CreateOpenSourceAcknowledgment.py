def _group_licenses(packages: list[dict]) -> dict:
	"""Groups packages by SPDX id, choosing a representative verbatim text per license."""
	groups: dict[str, dict] = {}
	for pkg in packages:
		spdx = pkg['spdx'] or pkg['license_name']
		grp = groups.setdefault(spdx, {'packages': set(), 'text': ''})
		grp['packages'].add(pkg['name'])
		# Keep the longest available text as the representative one.
		if len(pkg['license_text'] or '') > len(grp['text']):
			grp['text'] = pkg['license_text'] or ''
	return dict(sorted(groups.items(), key=lambda kv: _SPDX_NAMES.get(kv[0], kv[0]).lower()))


# ----------------------------------------------------------------------------------------------
# OSI inventory XML rendering (Inventory.xsd schema)
# ----------------------------------------------------------------------------------------------
def _xml_escape(text: str) -> str:
	"""Escapes XML special characters and encodes non-ASCII as numeric character references."""
	out: list[str] = []
	for ch in text or '':
		if ch == '&':
			out.append('&amp;')
		elif ch == '<':
			out.append('&lt;')
		elif ch == '>':
			out.append('&gt;')
		elif ord(ch) > 126:
			out.append(f'&#{ord(ch)};')
		else:
			out.append(ch)
	return ''.join(out)


def render_inventory_xml(packages: list[dict], output: str) -> None:
	"""Writes the OSI open source inventory XML (matches the ``Inventory.xsd`` schema)."""
	lines: list[str] = []
	lines.append(
		'<Inventory xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
		'xsi:noNamespaceSchemaLocation="Inventory.xsd">'
	)
	lines.append('    <OpenSourceModules>')
	for pkg in packages:
		license_ref = pkg.get('spdx') or pkg.get('license_name') or ''
		lines.append('        <Module>')
		lines.append(f'            <Modulename>{_xml_escape(pkg["name"])}</Modulename>')
		lines.append(f'            <Version>{_xml_escape(pkg["version"])}</Version>')
		lines.append(f'            <LicenseDbReference>{_xml_escape(license_ref)}</LicenseDbReference>')
		lines.append(f'            <Origin>{_xml_escape(pkg.get("origin", ""))}</Origin>')
		lines.append(f'            <Copyright>{_xml_escape(pkg.get("copyright", ""))}</Copyright>')
		lines.append('        </Module>')
	lines.append('    </OpenSourceModules>')
	lines.append('</Inventory>')

	with open(output, 'w', encoding='utf-8', newline='\n') as fh:
		fh.write('\n'.join(lines) + '\n')


